async def open_login_async(url: str, timeout_ms: int = LOGIN_WAIT_MS) -> str:
    """
    打开有头持久化浏览器让用户手动登录（扫码/账号密码都行）。
    登录完成后关闭窗口即可，会话保存在 .browser_profiles/<平台>/，后续解析自动复用。
    """
    pf = detect_platform_loose(url) or "xiaoe"
    async with async_playwright() as p:
        try:
            ctx = await _new_persistent_ctx(p, pf, headless=False)
        except Exception as e:
            return f"❌ 浏览器启动失败（是否已有一个登录窗口开着？）: {e}"

        page = ctx.pages[0] if ctx.pages else await ctx.new_page()
        try:
            await page.goto(url, wait_until="domcontentloaded", timeout=60000)
        except Exception:
            pass

        deadline = time.monotonic() + timeout_ms / 1000.0
        saved = False
        while time.monotonic() < deadline:
            await asyncio.sleep(2)
            try:
                if not ctx.pages:  # 用户关掉了窗口
                    break
                if await _dump_cookies(ctx, pf):
                    saved = True
            except Exception:
                break  # context 已关闭

        try:
            await ctx.close()
        except Exception:
            pass

    if saved:
        return f"✅ 登录态已保存（{pf}）。现在回到上面点『一键解析』即可，无头模式可以保持勾选。"
    return "⚠️ 未捕获到登录态：请确认在弹出的窗口里完成了登录，再关闭窗口。"

def open_login(url: str, timeout_ms: int = LOGIN_WAIT_MS) -> str:
    return asyncio.run(open_login_async(url, timeout_ms))
