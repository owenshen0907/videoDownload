# ---------------------------------------------------------------- 媒体判定

_MEDIA_EXT = re.compile(r"\.(m3u8|mp4|m4s)(\?|$)", re.I)

# 小鹅通视频走腾讯云点播 / 自有 CDN，常见承载域名
_XIAOE_MEDIA_HOST = re.compile(
    r"(xiaoeknow\.com|xiaoe-tech\.com|xet\.tech|xeknow\.com|myqcloud\.com|qcloudcdn|qcloud\.com|vod[0-9a-z\-]*\.)",
    re.I,
)

def _is_douyin_media(u: str) -> bool:
    return "douyinvod.com" in u and ("mime_type=video_mp4" in u or u.endswith(".mp4"))

def _is_xiaoe_media(u: str) -> bool:
    p = urlparse(u)
    path = p.path or ""
    if not _MEDIA_EXT.search(path):
        return False
    # .ts 分片不要；m3u8 一律收（含商家自有 CDN），mp4 只收已知媒体域名，避免收到页面里的小素材
    if path.lower().rstrip("/").endswith(".m3u8") or ".m3u8" in path.lower():
        return True
    return bool(_XIAOE_MEDIA_HOST.search(p.netloc or ""))

def _media_score(u: str) -> int:
    """m3u8 优先于 mp4；master/主清单优先于码率子清单。"""
    low = u.lower()
    if ".m3u8" in low:
        if "playlist_eof" in low:      # 直播回放的完整清单
            return 25
        # 形如 xxx.f230.m3u8 / v.f421220.m3u8 是单码率子清单，主清单优先
        return 15 if re.search(r"\.f\d+\.m3u8", low) else 20
    return 5

# ---------------------------------------------------------------- cookie 导出

async def _dump_cookies(ctx, platform: str) -> Optional[Path]:
    """
    把 Playwright context 里的 cookie 导出成 Netscape 格式，供 yt-dlp 复用登录态。
    """
    try:
        cookies = await ctx.cookies()
    except Exception:
        return None
    if not cookies:
        return None

    lines = ["# Netscape HTTP Cookie File", "# generated by videoDownload", ""]
    fallback_exp = int(time.time()) + 7 * 86400
    for c in cookies:
        domain = c.get("domain") or ""
        if not domain:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        secure = "TRUE" if c.get("secure") else "FALSE"
        try:
            expires = int(c.get("expires") or 0)
        except Exception:
            expires = 0
        if expires <= 0:
            expires = fallback_exp
        name = (c.get("name") or "").replace("\t", "").replace("\n", "")
        value = (c.get("value") or "").replace("\t", "").replace("\n", "")
        if not name:
            continue
        lines.append("\t".join([
            domain, include_sub, c.get("path") or "/", secure,
            str(expires), name, value,
        ]))

    path = cookie_file_for(platform)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path

